package com.conectebem.backend.dto;

/**
 * Dados de uma ONG devolvidos pela API ao frontend.
 *
 * <p>O {@code usuarioId} não é exposto porque é um vínculo interno do sistema.
 * A autenticação deve obter esse usuário pelo token, e não pelo retorno público da ONG.</p>
 */
public class OngResponseDTO {

    private Integer id;
    private String nome;
    private String cnpj;
    private String descricao;
    private String telefone;
    private String cidade;
    private String estado;

    public Integer getId() {
        return id;
    }

    public void setId(Integer id) {
        this.id = id;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public String getCnpj() {
        return cnpj;
    }

    public void setCnpj(String cnpj) {
        this.cnpj = cnpj;
    }

    public String getDescricao() {
        return descricao;
    }

    public void setDescricao(String descricao) {
        this.descricao = descricao;
    }

    public String getTelefone() {
        return telefone;
    }

    public void setTelefone(String telefone) {
        this.telefone = telefone;
    }

    public String getCidade() {
        return cidade;
    }

    public void setCidade(String cidade) {
        this.cidade = cidade;
    }

    public String getEstado() {
        return estado;
    }

    public void setEstado(String estado) {
        this.estado = estado;
    }
}
